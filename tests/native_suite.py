#!/usr/bin/python3
"""Native library regression suite; shared private desktop helpers are in native_support."""
from pathlib import Path
from native_support import (library,open_game,press_revealed,reveal,Atspi,BINARY,ROOT,SCALE,check,checked,children,db,escaped,find,focused_name,gi,json,logs,nodes,os,press,qt,report,restart,scalar,subprocess,text,time,uuid,visible,wait)

try:
    search=wait(lambda:find('Search games','text'))
    check('native-search-editable',search.get_editable_text_iface() is not None)
    state=qt('state');check('actual-window-dpr',abs(state['dpr']-SCALE)<.01)
    press('Add game');wait(lambda:find('Game name','text'))
    check('editor-initial-focus',wait(lambda:focused_name('Game name')))
    qt('key',sequence='Tab');check('editor-tab-focus',wait(lambda:focused_name('Runner settings')))
    qt('key',sequence='Shift+Tab');check('editor-backtab-focus',wait(lambda:focused_name('Game name')))
    press('Save profile');check('invalid-save-no-partial-entry',scalar('SELECT count(*) FROM games')==0)
    text('Game name','Native fixture 🦀 <b>literal</b>')
    fixture=os.fsencode(ROOT)+b'/foreign-game_\xff'
    descriptor=os.open(fixture,os.O_CREAT|os.O_EXCL|os.O_WRONLY,0o600);os.write(descriptor,b'not executable; preserve this fixture');os.close(descriptor)
    press('Exact Unix bytes','check box');wait(lambda:checked('Exact Unix bytes'))
    text('Executable path',escaped(fixture))
    press('Add argument');wait(lambda:find('Argument 1','text'))
    press('Add argument');text('Argument 2',r'one token ;$(never)\\quoted\xff')
    press('Add variable');text('Environment key 1','EMPTY')
    press('Add variable');text('Environment key 2','UNSET');press('Unset variable 2','check box')
    press('Save profile')
    wait(lambda:scalar('SELECT count(*) FROM games')==1)
    wait(lambda:find('Configure','button').get_state_set().contains(Atspi.StateType.ENABLED))
    with db() as connection:
        game=connection.execute('SELECT id,display_name FROM games').fetchone()
        profile=connection.execute('SELECT executable,cwd,revision FROM profiles').fetchone()
        arguments=connection.execute('SELECT value FROM arguments ORDER BY position').fetchall()
        environment=connection.execute('SELECT key,value FROM environment ORDER BY position').fetchall()
    check('native-create-unicode-and-raw-path',game[1]=='Native fixture 🦀 <b>literal</b>' and profile[0]==fixture and profile[1]==os.fsencode(ROOT))
    check('native-empty-token-and-literal-shell-bytes',arguments==[(b'',),(b'one token ;$(never)\\quoted\xff',)])
    check('native-set-empty-versus-unset',environment==[(b'EMPTY',b''),(b'UNSET',None)])
    literal=qt('state');check('user-labels-render-as-literal-text',literal['literalLabels']>0 and literal['richUserLabels']==0)
    check('save-opens-game-and-focuses-play',wait(lambda:focused_name('Play')))
    library()
    item=wait(lambda:find('Native fixture 🦀 <b>literal</b>','list item'))
    check('native-list-selection',item.get_state_set().contains(Atspi.StateType.SELECTED))
    open_game('Native fixture 🦀 <b>literal</b>')
    press('Configure');wait(lambda:find('Game name','text'))
    text('Game name','Unsaved draft')
    qt('close');wait(lambda:visible('Keep editing','button'))
    check('discard-dialog-focuses-keep-editing',wait(lambda:focused_name('Keep editing')))
    press('Keep editing');check('dirty-close-cancel-retains-draft',Atspi.Text.get_text(find('Game name','text'),0,-1)=='Unsaved draft')
    press('Library');wait(lambda:visible('Discard changes','button'))
    check('dirty-navigation-asks-before-discarding',visible('Game name','text') is not None)
    press('Keep editing');wait(lambda:not visible('Discard changes','button'))
    check('dirty-navigation-cancel-keeps-editor',Atspi.Text.get_text(find('Game name','text'),0,-1)=='Unsaved draft' and visible('Save profile','button') is not None)
    qt('key',sequence='Escape');wait(lambda:not visible('Save profile','button'))
    check('escape-returns-focus-and-preserves-commit',wait(lambda:focused_name('Play')) and scalar('SELECT display_name FROM games')=='Native fixture 🦀 <b>literal</b>')
    press('Add favorite');wait(lambda:scalar('SELECT favorite FROM games')==1)
    press('Favorites');check('favorites-derived-list',wait(lambda:find('Native fixture 🦀 <b>literal</b>','list item')) is not None)
    text('Search games','no match');wait(lambda:find('No games match these filters'))
    check('filter-keeps-selected-identity',scalar('SELECT selected_game FROM ui_state')==game[0])
    qt('key',sequence='Ctrl+F');check('search-shortcut-focus',wait(lambda:focused_name('Search games')))
    text('Search games','native');wait(lambda:find('Native fixture 🦀 <b>literal</b>','list item'))
    open_game('Native fixture 🦀 <b>literal</b>')
    press('Configure');wait(lambda:find('Game name','text'))
    check('raw-profile-auto-exact-mode',checked('Exact Unix bytes'))
    text('Game name','Edited fixture 🦀');press('Save profile')
    wait(lambda:scalar('SELECT revision FROM profiles')==2)
    check('edit-retains-exact-path',scalar('SELECT executable FROM profiles')==fixture)
    press('Settings');wait(lambda:find('Opaque panels','check box'))
    press('Opaque panels','check box');wait(lambda:checked('Opaque panels'))
    press('Reduce motion','check box');wait(lambda:checked('Reduce motion'))
    press('Done');wait(lambda:not visible('Done','button'))
    check('preferences-written',(ROOT/'config/rustris/config.toml').read_text().count('true')==2)
    restart();wait(lambda:find('Edited fixture 🦀','list item'))
    check('restart-retains-identities-and-configuration',scalar('SELECT id FROM games')==game[0] and scalar('SELECT executable FROM profiles')==fixture and scalar('SELECT revision FROM profiles')==2)
    press('Settings');wait(lambda:find('Opaque panels','check box'))
    check('restart-retains-preferences',checked('Opaque panels') and checked('Reduce motion'));press('Done')
    open_game('Edited fixture 🦀')
    # A real lock failure must remain visible and leave committed state unchanged.
    lock=db();lock.execute('BEGIN IMMEDIATE')
    press('Remove favorite');wait(lambda:any('locked' in n.get_name().lower() for n in nodes()))
    check('failed-write-remains-honest',scalar('SELECT favorite FROM games')==1)
    lock.rollback();lock.close();press('Reload library')
    for _ in range(25):
        qt('recreate');wait(lambda:find('Edited fixture 🦀','list item'))
    check('twenty-five-view-destructions-with-work-pending',True)
    qt('resize',width=980,height=660)
    state=qt('state');check('minimum-window-geometry',state['width']==980 and state['height']==660)
    qt('resize',width=1440,height=900);qt('screenshot')
    check('rendered-png',(ROOT/'screenshot.png').read_bytes().startswith(b'\x89PNG'))
    open_game('Edited fixture 🦀')
    press_revealed('Remove from library');wait(lambda:visible('Remove entry','button'))
    check('remove-dialog-focuses-cancel',wait(lambda:focused_name('Cancel')))
    qt('key',sequence='Space');wait(lambda:not visible('Remove entry','button'))
    check('remove-dialog-keyboard-cancel-preserves-entry',scalar('SELECT count(*) FROM games')==1)
    press_revealed('Remove from library');wait(lambda:visible('Remove entry','button'))
    press('Remove entry');wait(lambda:scalar('SELECT count(*) FROM games')==0)
    check('remove-keeps-foreign-file',Path(os.fsdecode(fixture)).read_bytes()==b'not executable; preserve this fixture')
    check('remove-cascades-owned-profile',scalar('SELECT count(*) FROM profiles')==0)
    with db() as connection:
        for number in range(1000):
            game_id=uuid.uuid4().bytes;install_id=uuid.uuid4().bytes;profile_id=uuid.uuid4().bytes
            connection.execute('INSERT INTO games(id,display_name) VALUES(?,?)',(game_id,f'Fixture Game {number:04}'))
            connection.execute('INSERT INTO installations(id,game_id) VALUES(?,?)',(install_id,game_id))
            connection.execute('INSERT INTO profiles(id,installation_id,executable,cwd,runner) VALUES(?,?,?,?,?)',(profile_id,install_id,os.fsencode(ROOT/f'missing-{number}'),os.fsencode(ROOT),'native'))
        connection.execute('UPDATE ui_state SET selected_game=?',(game_id,))
    restart()
    wait(lambda:find('Fixture Game 0999','list item'))
    started=time.monotonic();text('Search games','0999')
    wait(lambda:find('Showing 1 of 1,000') or find('Showing 1 of 1000'))
    report['metrics']['1000_entry_filter_with_native_observation_ms']=round((time.monotonic()-started)*1000,2)
    check('thousand-entry-filter-and-selected-identity',scalar('SELECT selected_game FROM ui_state')==game_id)
    text('Search games','')
    wait(lambda:find('Showing 1,000 of 1,000') or find('Showing 1000 of 1000'))
    qt('screenshot')
    if children:
        status=Path(f'/proc/{children[-1].pid}/status').read_text()
        report['metrics']['populated_rss_kib']=int(next(line.split()[1] for line in status.splitlines() if line.startswith('VmRSS:')))
    press('Settings');wait(lambda:find('Opaque panels','check box'))
    press('Opaque panels','check box');qt('close')
    wait(lambda:find('Rustris','application') is None)
    check('close-drains-accepted-preference-write','opaque = false' in (ROOT/'config/rustris/config.toml').read_text())
    wait(lambda:children[-1].poll() is not None)
    check('normal-close-exits-successfully',children[-1].returncode==0)
    report['passed']=True
except Exception as error:
    report['passed']=False;report['error']=str(error)
    report['tree']=[]
    for n in nodes():
        try:report['tree'].append({'name':n.get_name(),'role':n.get_role_name()})
        except gi.repository.GLib.Error:pass
    raise
finally:
    (ROOT/'report.json').write_text(json.dumps(report,indent=2))
    for process in children:
        if process.poll() is None:
            process.terminate()
            try:process.wait(timeout=5)
            except subprocess.TimeoutExpired:process.kill();process.wait()
    for log in logs:log.close()
